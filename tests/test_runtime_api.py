class OfflineContractRunner:
    """Explicit test double: never selected by production application."""
    def __init__(self,store,docs,source,fixture,fail_once=False):
        self.store=store;self.docs=docs;self.source=source;self.fixture=fixture;self.fail_once=fail_once;self.created=[];self.submitted=[];self.config=Connection(poll_seconds=0)
    def check(self):return {'agent_available':True,'version':'2.0.32'}
    def models(self):return [{'providerID':'test','id':'ds'},{'providerID':'test','id':'glm'}]
    def session(self,id):
        if id not in self.created:raise RunnerError('missing',404)
        return {'id':id}
    def request(self,method,path,**kwargs):
        assert method=='POST' and path=='/api/session';self.created.append(kwargs['json']['id']);return {'data':{'id':kwargs['json']['id']}}
    def messages(self,sid):return []
    def submit(self,sid,message_id,text):self.submitted.append((sid,message_id));return {}
    def cancel(self,sid):return {'interrupted':True}
    def poll(self,sid,model,cancelled,on_checkpoint,budget,after_message_id=None):
        on_checkpoint({'session_id':sid,'session':{'id':sid,'tokens':{'input':10,'output':5},'cost':.01},'messages':[]})
        if self.fail_once:self.fail_once=False;raise RunnerError('test disconnect')
        run=next(r for r in self.store.list('run') if r.get('active_session')==sid);g=run['candidate'];patch={'operations':[],'root_module_id':self.fixture['root_module_id']}
        if not g['nodes']:
            for collection in ['evidence','nodes','relations']:
                for row in self.fixture[collection]:patch['operations'].append({'collection':collection,'op':'add','id':row['id'],'after':deepcopy(row),'reason':'controlled fixture only'})
        tools=Tools(self.store,self.docs)
        c=run['current_chunk'];tools.call('fkg_read',{'run_id':run['id'],'source_id':self.source['id'],'document_id':c['document_id'],'line_start':c['line_start'],'line_end':c['line_end']})
        assert tools.call('fkg_validate',{'run_id':run['id'],'patch':patch})['valid']
        artifact=tools.call('fkg_stage',{'run_id':run['id'],'patch':patch})['artifact_id']
        return {'text':json.dumps({'artifact_id':artifact}),'tools':[{'name':'fkg_read','state':{'status':'completed'}},{'name':'fkg_validate','state':{'status':'completed'}}]}

def jobs_for_sample(sample,fail=False):
    store,docs,src,g,tmp=sample
    # Single deterministic source chunk, isolated fixture; semantic contents are NOT generated by the test.
    src['chunks']=[dict(src['chunks'][0],quote='fixture transport contract')];store.put('source',src)
    store.put('config',{'models':{'DeepSeek v4 flash':{'providerID':'test','id':'ds'},'GLM 5.3':{'providerID':'test','id':'glm'}},'max_tokens':None,'max_usd':None,'timeout_seconds':10,'max_candidate_attempts':3,'concurrency':1},id='runtime')
    runner=OfflineContractRunner(store,docs,src,g,fail);jobs=Jobs(store,docs,runner,start=False)
    return store,docs,src,g,runner,jobs

def test_generation_contract_idempotency_and_actual_tool_artifact(sample):
    store,docs,src,g,runner,jobs=jobs_for_sample(sample)
    req={'mode':'generate','source_id':src['id'],'model_label':'DeepSeek v4 flash'}
    run=jobs.submit(req,'key');assert jobs.submit(req,'key')['id']==run['id']
    with pytest.raises(ValueError,match='different request'):jobs.submit(dict(req,model_label='GLM 5.3'),'key')
    jobs.execute(run['id']);r=store.get('run',run['id'])
    assert r['status']=='succeeded';assert r['usage']['tokens']=={'input':10,'output':5,'reasoning':0}
    assert r['usage']['usd']==.01;assert r['artifacts'];assert len(runner.created)==1
    assert store.get('graph',r['graph_id'])['nodes']==g['nodes']

